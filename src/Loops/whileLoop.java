package Loops;

public class whileLoop {
    static void main() {
        System.out.println(1);
        System.out.println(2);
        System.out.println(3);

        int i = 1;
        while(i<=3){
            System.out.println(i);
            i++;
        } //jab tak condition true tab tak execute hoga.
        //if condition false nhi hoga, tab tak loop execute hote rhega.
    }
}

